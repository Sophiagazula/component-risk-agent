"""
Feature ablation: does each signal earn its place?

Retrains the P50 model on the same 8 backtest origins with one feature group
removed at a time and compares WAPE with the full model. Writes
data/evaluation.json and reports/evaluation.md.
"""
import json

import numpy as np

from model import DATA, ROOT, H, ForecastData, wape

fd = ForecastData.from_csv()
bt_origins, _ = fd.origins()

VARIANTS = [
    ("All features", ()),
    ("Without sales pipeline", ("pipeline",)),
    ("Without same month last year", ("same_month_ly",)),
    ("Without calendar month", ("target_month",)),
    ("Without trend", ("trend_yoy",)),
    ("History only (no pipeline, calendar or trend)", ("pipeline", "target_month", "trend_yoy")),
]


def backtest_p50(drop):
    actual, pred = [], []
    for o in bt_origins:
        logq, meta, *_ = fd.predict_origin(o, quantiles=[0.5], drop=drop)
        for k, (h, p) in enumerate(meta):
            actual.append(fd.Y[o + h, p])
            pred.append(np.expm1(logq[k, 0]))
    return wape(actual, pred)


results = []
for name, drop in VARIANTS:
    w = backtest_p50(drop)
    results.append({"variant": name, "dropped": list(drop), "wape": w})
    print(f"{name:48s} WAPE {w:.3f}")
full = results[0]["wape"]
for r in results:
    r["change_vs_full"] = r["wape"] - full

summary = json.loads((DATA / "backtest_summary.json").read_text())
evaluation = {"ablation": results, "by_horizon": {h: s["wape_model"] for h, s in summary["by_horizon"].items()},
              "reliability": summary["reliability"]}
(DATA / "evaluation.json").write_text(json.dumps(evaluation, indent=2))

lines = ["# Model evaluation", "",
         f"Rolling backtest, {len(bt_origins)} forecast origins ({fd.months[bt_origins[0]]} to {fd.months[bt_origins[-1]]}), "
         f"1-{H} months ahead, 6 devices. Generated by `src/evaluate.py`.", "",
         "## Feature ablation (P50 model)", "", "| Variant | WAPE | Change vs. all features |", "|---|---|---|"]
lines += [f"| {r['variant']} | {r['wape']:.1%} | {r['change_vs_full']:+.1%} |" for r in results]
lines += ["", "## Error by months ahead", "", "| Months ahead | WAPE |", "|---|---|"]
lines += [f"| {h} | {w:.1%} |" for h, w in evaluation["by_horizon"].items()]
lines += ["", "## Calibration", "", "Share of actuals at or below each predicted quantile. A calibrated model matches the quantile.", "",
          "| Quantile | Raw model | Calibrated |", "|---|---|---|"]
lines += [f"| P{round(float(q) * 100)} | {summary['reliability']['raw'][q]:.0%} | {summary['reliability']['calibrated'][q]:.0%} |"
          for q in summary["reliability"]["raw"]]
(ROOT / "reports").mkdir(exist_ok=True)
(ROOT / "reports" / "evaluation.md").write_text("\n".join(lines) + "\n")
print("wrote reports/evaluation.md")
